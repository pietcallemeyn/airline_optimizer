def available(pid,m,avail):
    d=m.departure.date()
    while d<=m.arrival.date():
        if avail.get((pid,d),'AVAILABLE') in BLOCKING: return False
        d+=timedelta(days=1)
    return True

def duty_interval(m): return m.departure-timedelta(minutes=REPORT_MIN),m.arrival+timedelta(minutes=RELEASE_MIN)
def overlap(a,b): return a[0]<b[1] and b[0]<a[1]

def _clock_min(x):
    return x.hour*60+x.minute

def max_fdp_minutes(start, sectors):
    """Basic max FDP for acclimatised crew from the supplied table."""
    idx = 0 if sectors <= 2 else min(sectors,10)-2
    cm = _clock_min(fdp_reference_start(start))
    if cm >= 17*60 or cm <= 4*60+59:
        return FDP_1700_0459[idx]
    for lo,hi,vals in FDP_TABLE:
        lom=lo[0]*60+lo[1]; him=hi[0]*60+hi[1]
        if lom <= cm <= him:
            return vals[idx]
    raise ValueError(f"No FDP table band for reference start {fdp_reference_start(start):%H:%M %Z}")

def split_duty_for_period(items):
    """Return the best usable split-duty break inside one FDP, if any.

    Ground interval is measured landing-to-next-takeoff. One hour is removed
    for the specified post-flight/travel/pre-flight activities. The remaining
    protected break must be at least 3h. At most 6h of that break earns credit,
    and the FDP extension is 50% of the creditable break.

    WOCL encroachment and accommodation availability are not represented in
    the current input data, so they are deliberately not inferred here.
    """
    seq=sorted(items,key=lambda m:(m.departure,m.id))
    best=None
    for prev,nxt in zip(seq,seq[1:]):
        ground=max(0,int((nxt.departure-prev.arrival).total_seconds()//60))
        protected=max(0,ground-SPLIT_OVERHEAD_MIN)
        if protected < SPLIT_MIN_BREAK_MIN:
            continue
        creditable=min(protected,SPLIT_MAX_CREDITABLE_BREAK_MIN)
        extension=creditable//2
        candidate={'after_mission':prev.id,'before_mission':nxt.id,
                   'station':prev.destination,'ground_break_min':ground,
                   'protected_break_min':protected,'creditable_break_min':creditable,
                   'extension_min':extension}
        if best is None or (candidate['extension_min'],candidate['protected_break_min']) > (best['extension_min'],best['protected_break_min']):
            best=candidate
    return best

def fdp_limit_for_period(items):
    seq=sorted(items,key=lambda m:(m.departure,m.id))
    start=seq[0].departure-timedelta(minutes=REPORT_MIN)
    basic=max_fdp_minutes(start,len(seq))
    split=split_duty_for_period(seq)
    extension=split['extension_min'] if split else 0
    return basic, basic+extension, split

def duty_periods_for_missions(ms):
    """Infer FDP/duty periods from the mission sequence.

    Do NOT split at UTC midnight. A sequence of sectors remains one duty until
    there is enough time for a legal rest before the next report. This avoids
    falsely treating an overnight continuation as a new duty with negative rest.
    """
    seq=sorted(ms,key=lambda x:(x.departure,x.id))
    if not seq:
        return []

    periods=[]
    current=[seq[0]]

    def period_values(items):
        start=items[0].departure-timedelta(minutes=REPORT_MIN)
        end=max(m.arrival for m in items)+timedelta(minutes=RELEASE_MIN)
        return start,end,int((end-start).total_seconds()//60)

    for m in seq[1:]:
        pstart,pend,pdur=period_values(current)
        next_report=m.departure-timedelta(minutes=REPORT_MIN)
        rest=int((next_report-pend).total_seconds()//60)

        # A new FDP can only start if the preceding duty has received the
        # required minimum rest. Use the next sector's origin to distinguish
        # home-base and away-from-base rest.
        min_rest=max(pdur, 12*60 if m.origin in BASES else 10*60)
        if rest >= min_rest:
            periods.append(current)
            current=[m]
        else:
            current.append(m)

    periods.append(current)

    out=[]
    for items in periods:
        start,end,duty_min=period_values(items)
        out.append({
            'day':start.date(),
            'start':start,
            'end':end,
            'sectors':len(items),
            'duty_min':duty_min,
            'fdp_min':int((max(m.arrival for m in items)-start).total_seconds()//60),
            'flight_min':sum(int((m.arrival-m.departure).total_seconds()//60) for m in items),
            'missions':items,
        })
    return out

def _rolling_limit_ok(duties, field, days, limit):
    if not duties: return True
    totals={}
    for x in duties:
        totals[x['day']]=totals.get(x['day'],0)+x[field]
    dates=sorted(totals)
    for end in dates:
        start=end-timedelta(days=days-1)
        total=sum(v for d,v in totals.items() if start<=d<=end)
        if total>limit:
            return False
    return True

def ftl_ok_for_missions(ms, home_base=None):
    duties=duty_periods_for_missions(ms)

    # Daily FDP limit, including an automatically detected legal split duty.
    for x in duties:
        if x['sectors']>10:
            return False
        basic,allowed,split=fdp_limit_for_period(x['missions'])
        if x['fdp_min']>allowed:
            return False

    # Rest between inferred consecutive FDPs. Normally this is already assured
    # by the splitter, but check it explicitly as a hard validation.
    for prev,nxt in zip(duties,duties[1:]):
        rest=int((nxt['start']-prev['end']).total_seconds()//60)
        next_first=nxt['missions'][0]
        at_home = (next_first.origin == home_base) if home_base else (next_first.origin in BASES)
        minimum=max(prev['duty_min'], 12*60 if at_home else 10*60)
        if rest < minimum:
            return False

    if not _rolling_limit_ok(duties,'duty_min',7,MAX_DUTY_7D_MIN): return False
    if not _rolling_limit_ok(duties,'duty_min',14,MAX_DUTY_14D_MIN): return False
    if not _rolling_limit_ok(duties,'duty_min',28,MAX_DUTY_28D_MIN): return False
    if not _rolling_limit_ok(duties,'flight_min',28,MAX_FLIGHT_28D_MIN): return False
    return True




# Flight-window policy: no prior duty history and no reserve duty.
# Timestamps are local wall-clock values; the input must use one consistent
# local clock. Protected local night: 22:00-06:00 (configurable assumption).
RECOVERY_HOURS = 36
RECOVERY_MAX_INTERVAL_HOURS = 168
LOCAL_NIGHT_START = 22
LOCAL_NIGHT_END = 6

def _local_nights(start, end):
    day = start.date() - timedelta(days=1)
    count = 0
    while datetime.combine(day, datetime.min.time()) <= end:
        night = datetime.combine(day, datetime.min.time()).replace(hour=LOCAL_NIGHT_START)
        night_end = night + timedelta(hours=(24-LOCAL_NIGHT_START+LOCAL_NIGHT_END))
        if start <= night and night_end <= end:
            count += 1
        day += timedelta(days=1)
    return count

def _month_next(month):
    return (month.replace(day=28) + timedelta(days=4)).replace(day=1)

def recovery_rest_checks(roster, window_start, window_end):
    """Return independently displayable recovery checks for a complete roster.

    Initial 168-hour clock is reset at the first flight-window departure.
    An eligible 36-hour recovery rest must START within 168h of the last
    eligible recovery rest END; no prior-window history is assumed.
    """
    duties = duty_periods_for_missions(roster)
    rest = []
    cursor = window_start
    for duty in duties:
        begin, finish = duty['start'], duty['end']
        if finish <= window_start or begin >= window_end:
            continue
        if begin > cursor:
            rest.append((cursor, min(begin, window_end)))
        cursor = max(cursor, min(finish, window_end))
    if cursor < window_end:
        rest.append((cursor, window_end))
    qualifying = [(a,b) for a,b in rest if (b-a)>=timedelta(hours=RECOVERY_HOURS) and _local_nights(a,b)>=2]
    last_end = window_start
    max_gap = timedelta(hours=RECOVERY_MAX_INTERVAL_HOURS)
    recurrence = True
    for a,b in qualifying:
        if a-last_end > max_gap:
            recurrence = False
        last_end = b
    if window_end-last_end > max_gap:
        recurrence = False
    # A partial month is NOT assessed; only a fully enclosed calendar month.
    month = window_start.replace(day=1,hour=0,minute=0,second=0,microsecond=0)
    monthly = []
    while month < window_end:
        next_month = _month_next(month)
        if window_start <= month and next_month <= window_end:
            # Two separate, nonoverlapping 48h blocks, each spanning two full
            # local calendar days, within this calendar month.
            blocks = []
            for a,b in rest:
                left,right = max(a,month),min(b,next_month)
                midnight = datetime.combine(left.date(),datetime.min.time())
                if midnight < left:
                    midnight += timedelta(days=1)
                while midnight + timedelta(days=2) <= right:
                    blocks.append((midnight,midnight+timedelta(days=2)))
                    midnight += timedelta(days=2)
            blocks.sort()
            chosen=[]
            for a,b in blocks:
                if not chosen or a >= chosen[-1][1]:
                    chosen.append((a,b))
            monthly.append({'month':month.strftime('%Y-%m'),'passed':len(chosen)>=2,'count':len(chosen)})
        month = next_month
    return {'recurrent_36h_2_local_nights_168h':recurrence,
            'monthly_two_48h_rest':all(x['passed'] for x in monthly),
            'monthly_assessed':bool(monthly), 'monthly_details':monthly,
            'qualifying_rests':len(qualifying)}

def pilot_ftl_checklist(roster, pilot, availability, window_start, window_end, assignments=None):
    """Recalculate FTL and eligibility for one pilot from saved movements."""
    duties = duty_periods_for_missions(roster)
    fdp_ok = all(x['sectors']<=10 and x['fdp_min']<=fdp_limit_for_period(x['missions'])[1] for x in duties)
    rest_ok = True
    for prev,nxt in zip(duties,duties[1:]):
        gap = int((nxt['start']-prev['end']).total_seconds()//60)
        home = nxt['missions'][0].origin == pilot.home_base
        if gap < max(prev['duty_min'],720 if home else 600):
            rest_ok = False
    no_overlap = all(not (a.departure < b.arrival and b.departure < a.arrival)
                     for i,a in enumerate(roster) for b in roster[i+1:])
    recovery = recovery_rest_checks(roster,window_start,window_end)
    checks = {
        'Pilot availability':all(available(pilot.id,m,availability) for m in roster),
        'No overlapping flights':no_overlap,
        'Daily FDP and sector limits':fdp_ok,
        'Minimum rest between duty periods':rest_ok,
        'Duty time: max. 60 hours / 7 days':_rolling_limit_ok(duties,'duty_min',7,MAX_DUTY_7D_MIN),
        'Duty time: max. 110 hours / 14 days':_rolling_limit_ok(duties,'duty_min',14,MAX_DUTY_14D_MIN),
        'Duty time: max. 190 hours / 28 days':_rolling_limit_ok(duties,'duty_min',28,MAX_DUTY_28D_MIN),
        'Flight time: max. 100 hours / 28 days':_rolling_limit_ok(duties,'flight_min',28,MAX_FLIGHT_28D_MIN),
        'Extended recovery rest: 36 hours, 2 local nights, max. 168 hours':recovery['recurrent_36h_2_local_nights_168h'],
    }
    if assignments is not None:
        checks['Experienced pilot in each crew']=all(assignments.get(m.id,{}).get('experienced_pair',False) for m in roster)
    monthly_status = 'PASS' if recovery['monthly_two_48h_rest'] else 'FAIL'
    if not recovery['monthly_assessed']:
        monthly_status = 'NOT ASSESSED (no complete calendar month)'
    return {'checks':checks,'monthly_status':monthly_status,'recovery':recovery,
            'duties':len(duties),'flights':len(roster)}

def diagnose_ftl_failure(missions, pilots, avail, caps, fos):
    """Report full-tour coverage limitations (relief may still be feasible)."""
    tours=build_tours(missions)
    mission_by_id = {m.id: m for m in missions}
    normalized_tours = []
    for tour_entry in tours:
        # Preserve both pieces returned by build_tours():
        # (aircraft registration, list of Mission objects).
        if (
            isinstance(tour_entry, tuple)
            and len(tour_entry) == 2
            and isinstance(tour_entry[1], (list, tuple))
        ):
            reg, tour = tour_entry
        else:
            reg, tour = None, tour_entry

        normalized = []
        for item in tour:
            if isinstance(item, str):
                if item not in mission_by_id:
                    raise KeyError(f"Unknown mission id in tour: {item}")
                normalized.append(mission_by_id[item])
            else:
                normalized.append(item)

        if reg is None and normalized:
            reg = normalized[0].fixed_aircraft
        normalized_tours.append((reg, normalized))
    tours = normalized_tours
    print("\nFTL / TOUR FEASIBILITY DIAGNOSTIC")
    print("="*78)

    def availability_reasons(pid,tour):
        bad=[]
        for m in tour:
            d=m.departure.date()
            while d<=m.arrival.date():
                if avail.get((pid,d),'AVAILABLE') in BLOCKING:
                    bad.append(str(d))
                d+=timedelta(days=1)
        return sorted(set(bad))

    def ftl_reasons(tour):
        duties=duty_periods_for_missions(list(tour))
        reasons=[]
        for x in duties:
            if x['sectors']>10:
                reasons.append(f"{x['start']:%Y-%m-%d}: {x['sectors']} sectors (>10)")
            else:
                basic,allowed,split=fdp_limit_for_period(x['missions'])
                if x['fdp_min']>allowed:
                    split_txt=(f", split +{split['extension_min']//60:02d}:{split['extension_min']%60:02d} at {split['station']}" if split else "")
                    reasons.append(
                        f"{x['start']:%Y-%m-%d} FDP {x['fdp_min']//60:02d}:{x['fdp_min']%60:02d} "
                        f"> {allowed//60:02d}:{allowed%60:02d} allowed "
                        f"(basic {basic//60:02d}:{basic%60:02d}{split_txt}; {x['sectors']} sectors, report {x['start']:%H:%M})"
                    )
        if not _rolling_limit_ok(duties,'duty_min',7,MAX_DUTY_7D_MIN): reasons.append("60h/7d duty exceeded")
        if not _rolling_limit_ok(duties,'duty_min',14,MAX_DUTY_14D_MIN): reasons.append("110h/14d duty exceeded")
        if not _rolling_limit_ok(duties,'duty_min',28,MAX_DUTY_28D_MIN): reasons.append("190h/28d duty exceeded")
        if not _rolling_limit_ok(duties,'flight_min',28,MAX_FLIGHT_28D_MIN): reasons.append("100h/28d flight exceeded")
        return reasons

    impossible=0
    for ti,(reg,tour) in enumerate(tours,1):
        common_ftl=ftl_reasons(tour)
        cap_ok=[]; fo_ok=[]; cap_fail={}; fo_fail={}
        for pool,ok,fail in [(caps,cap_ok,cap_fail),(fos,fo_ok,fo_fail)]:
            for pid in pool:
                reasons=[]
                bad=availability_reasons(pid,tour)
                if bad: reasons.append("unavailable " + ",".join(bad[:5]))
                reasons.extend(common_ftl)
                if reasons: fail[pid]=reasons
                else: ok.append(pid)

        if not cap_ok or not fo_ok:
            impossible+=1
            print(f"\nTOUR {ti}: {reg} · {tour[0].departure:%Y-%m-%d %H:%M} -> {tour[-1].arrival:%Y-%m-%d %H:%M} · {len(tour)} sectors")
            print("  route:", " -> ".join([tour[0].origin]+[m.destination for m in tour]))
            print("  CAPT feasible:", ", ".join(cap_ok) if cap_ok else "NONE")
            print("  FO feasible:  ", ", ".join(fo_ok) if fo_ok else "NONE")
            if common_ftl:
                print("  TOUR FTL:")
                for r in common_ftl: print("   -",r)
            if not cap_ok:
                for pid,reasons in cap_fail.items():
                    if not common_ftl: print(f"    CAPT {pid}: " + "; ".join(reasons[:3]))
            if not fo_ok:
                for pid,reasons in fo_fail.items():
                    if not common_ftl: print(f"    FO {pid}: " + "; ".join(reasons[:3]))

    if not impossible:
        print("\nEvery tour has at least one individually feasible full-tour CAPT and FO.")
        print("The remaining failure is therefore caused by competition/overlap between tours.")
    else:
        print(f"\n{impossible} tour(s) lack a single-pilot full-tour CAPT and/or FO; coordinated relief may still work.")
    print("="*78)

def precompute(missions,pilots,avail):
    caps=[p.id for p in pilots.values() if p.role=='CAPT']; fos=[p.id for p in pilots.values() if p.role=='FO']
    feasible={}
    for m in missions:
        feasible[m.id]={'CAPT':[p for p in caps if available(p,m,avail)],'FO':[p for p in fos if available(p,m,avail)]}
        if not feasible[m.id]['CAPT'] or not feasible[m.id]['FO']:
            raise ValueError(f"{m.id} has no available {'captain' if not feasible[m.id]['CAPT'] else 'first officer'}")
    return feasible,caps,fos

def can_assign(pid,m,busy):
    iv=duty_interval(m)
    return all(not overlap(iv,x) for x in busy.get(pid,[]))

def build_tours(missions):
    """Split each fixed-aircraft sequence into crew tours.

    A crew stays attached while the aircraft is outstation. A tour ends only
    when the aircraft arrives at EBAW or EBLG. This makes outstation swaps
    impossible by construction instead of trying to enforce continuity one
    mission at a time in global chronological order.
    """
    by_aircraft={}
    for m in missions:
        by_aircraft.setdefault(m.fixed_aircraft,[]).append(m)
    tours=[]
    for reg, seq in by_aircraft.items():
        seq=sorted(seq,key=lambda m:(m.departure,m.id))
        current=[]
        for m in seq:
            current.append(m)
            if m.destination in BASES:
                tours.append((reg,current))
                current=[]
        if current:
            tours.append((reg,current))
    return sorted(tours,key=lambda x:(x[1][0].departure,x[0]))

def decode(keys, missions, feasible, caps, fos, avail, pilots, rng=None, failure_stats=None, fixed_tours=None):
    """Assign experienced-compatible CAPT/FO pairs, with joint relief search.

    Prefer one crew for a whole tour. If that is impossible, search coordinated
    pair segments with iterative deepening in the number of handover events.
    All candidates are checked against their accumulated pilot FTL rosters.
    """
    assigned = {p: [] for p in caps + fos}
    counts = {p: 0 for p in caps + fos}
    days = {p: set() for p in caps + fos}
    assign, meta, last_crew = {}, {}, {}
    gi = 0

    def pair_order(pairs):
        nonlocal gi
        pairs = sorted(pairs, key=lambda pair: (
            counts[pair[0]] + counts[pair[1]],
            len(days[pair[0]]) + len(days[pair[1]]), pair))
        if keys and len(pairs) > 1:
            # Vary ties and near-ties between GA chromosomes.
            width = max(1, (len(pairs) + 1) // 2)
            shift = min(width - 1, int(keys[gi % len(keys)] * width))
            gi += 1
            pairs = pairs[shift:] + pairs[:shift]
        return pairs

    for reg, tour in build_tours(missions):
        n = len(tour)
        # Availability and experience are immutable for this tour.
        possible = []
        for m in tour:
            cs = feasible[m.id]['CAPT']
            fs = feasible[m.id]['FO']
            possible.append([(c, f) for c in cs for f in fs
                             if pilots[c].experienced or pilots[f].experienced])
            if not possible[-1]:
                if failure_stats is not None:
                    failure_stats[(reg, "NO_EXPERIENCED_PAIR", m.id)] = failure_stats.get((reg, "NO_EXPERIENCED_PAIR", m.id), 0) + 1
                return None

        planned = {p: [] for p in caps + fos}
        legal_cache = {}

        def legal_segment(pid, role, start, end):
            segment = tour[start:end]
            old = assigned[pid] + planned[pid]
            key = (pid, role, start, end, tuple(x.id for x in planned[pid]))
            if key in legal_cache:
                return legal_cache[key]
            ok = (all(pid in feasible[m.id][role] for m in segment)
                  and all(available(pid, m, avail) for m in segment)
                  and all(not (a.departure < b.arrival and b.departure < a.arrival)
                          for j, a in enumerate(segment) for b in segment[j+1:])
                  and all(not (m.departure < x.arrival and x.departure < m.arrival)
                          for m in segment for x in old)
                  and ftl_ok_for_missions(old + segment, pilots[pid].home_base))
            legal_cache[key] = ok
            return ok

        def legal_pair(pair, start, end):
            c, f = pair
            return (legal_segment(c, 'CAPT', start, end)
                    and legal_segment(f, 'FO', start, end))

        # LNS: preserve the incumbent's crew assignments on frozen tours.
        # Unfrozen tours are rebuilt, and the complete schedule is validated.
        frozen = (fixed_tours or {}).get(tour[0].id)
        if frozen is not None:
            segments = []
            for i, m in enumerate(tour):
                pair = frozen.get(m.id)
                if pair is None or pair not in possible[i]:
                    return None
                if segments and segments[-1][2] == pair:
                    start, _, old_pair = segments[-1]
                    segments[-1] = (start, i + 1, old_pair)
                else:
                    segments.append((i, i + 1, pair))
            if not all(legal_pair(pair, a, b) for a, b, pair in segments):
                return None
        else:
            segments = None
        # Fast path: find a complete-tour pair before attempting any relief.
        common = set(possible[0])
        for options in possible[1:]:
            common.intersection_update(options)
        full = ([pair for pair in pair_order(common) if legal_pair(pair, 0, n)]
                if frozen is None else [])
        if frozen is not None:
            pass
        elif full:
            segments = [(0, n, full[0])]
        else:
            # Search pair segments jointly. Either role or both can change.
            # Cap expensive searches per tour so a difficult GA chromosome
            # cannot stall an entire optimization run.
            node_budget = 100000
            nodes = 0
            segments = None
            aborted = False

            for max_events in range(1, n):
                nodes = 0  # Reset the search allowance for each relief depth.
                failed = set()

                def search(start, previous_pair, events_left):
                    nonlocal nodes, aborted
                    nodes += 1
                    if nodes > node_budget:
                        aborted = True
                        return None
                    if start == n:
                        return []
                    if events_left < 0:
                        return None
                    state = (start, previous_pair, events_left,
                             tuple((p, tuple(m.id for m in planned[p]))
                                   for p in sorted(planned) if planned[p]))
                    if state in failed:
                        return None

                    # Longest segments first to minimize handover events.
                    for end in range(n, start, -1):
                        options = set(possible[start])
                        for j in range(start + 1, end):
                            options.intersection_update(possible[j])
                            if not options:
                                break
                        if not options:
                            continue
                        if end < n and events_left == 0:
                            continue
                        for pair in pair_order(options):
                            if pair == previous_pair:
                                continue
                            if not legal_pair(pair, start, end):
                                continue
                            c, f = pair
                            segment = tour[start:end]
                            planned[c].extend(segment)
                            planned[f].extend(segment)
                            tail = search(end, pair, events_left - (end < n))
                            del planned[c][-len(segment):]
                            del planned[f][-len(segment):]
                            if tail is not None:
                                return [(start, end, pair)] + tail
                            if aborted:
                                return None
                    failed.add(state)
                    return None

                segments = search(0, None, max_events)
                if segments is not None or aborted:
                    break
            if segments is None:
                if failure_stats is not None:
                    reason = "RELIEF_SEARCH_LIMIT" if aborted else "NO_LEGAL_RELIEF"
                    failure_stats[(reg, reason, str(n))] = failure_stats.get((reg, reason, str(n)), 0) + 1
                return None

        cap_at, fo_at = {}, {}
        for start, end, (c, f) in segments:
            for i in range(start, end):
                cap_at[i], fo_at[i] = c, f

        previous = last_crew.get(reg)
        for i, m in enumerate(tour):
            c, f = cap_at[i], fo_at[i]
            if not (pilots[c].experienced or pilots[f].experienced):
                return None
            if i == 0:
                changed_c = previous is not None and c != previous[0]
                changed_f = previous is not None and f != previous[1]
                if previous is None:
                    action, handover, changed, outstation = 'INITIAL_ATTACH', None, 0, False
                elif not changed_c and not changed_f:
                    action, handover, changed, outstation = 'CONTINUE', None, 0, False
                else:
                    action = ('BASE_FULL_CREW_SWAP' if changed_c and changed_f
                              else 'BASE_CAPT_SWAP' if changed_c else 'BASE_FO_SWAP')
                    handover, changed, outstation = m.origin, int(changed_c) + int(changed_f), False
            else:
                pc, pf = cap_at[i - 1], fo_at[i - 1]
                changed_c, changed_f = c != pc, f != pf
                changed = int(changed_c) + int(changed_f)
                if not changed:
                    action, handover, outstation = 'CONTINUE', None, False
                else:
                    outstation = m.origin not in BASES
                    prefix = 'OUTSTATION' if outstation else 'BASE'
                    action = (f'{prefix}_FULL_CREW_SWAP' if changed_c and changed_f
                              else f'{prefix}_CAPT_SWAP' if changed_c else f'{prefix}_FO_SWAP')
                    handover = m.origin
            assign[m.id] = {'captain': c, 'fo': f}
            meta[m.id] = {'action': action, 'handover_airport': handover,
                          'outstation': bool(outstation), 'changed_pilots': changed,
                          'reason': 'FTL_REQUIRED' if outstation else None}
            for pid in (c, f):
                assigned[pid].append(m)
                counts[pid] += 1
                days[pid].add(m.departure.date())
        last_crew[reg] = (cap_at[n - 1], fo_at[n - 1])

    # Mandatory final validation of experience, FTL and conflicting duties.
    for pair in assign.values():
        if not (pilots[pair['captain']].experienced or pilots[pair['fo']].experienced):
            return None
    for pid, roster in assigned.items():
        if not ftl_ok_for_missions(roster, pilots[pid].home_base):
            return None
        # Adjacent sectors of the SAME duty legitimately have overlapping
        # per-sector report/release windows.  Those windows are not separate
        # duties.  Reject actual flight overlaps here; cross-tour duty
        # conflicts have already been checked by legal_segment().
        for i, first in enumerate(roster):
            if any(first.departure < second.arrival
                   and second.departure < first.arrival
                   for second in roster[i + 1:]):
                if failure_stats is not None:
                    key = ('FINAL', 'FLIGHT_OVERLAP', pid)
                    failure_stats[key] = failure_stats.get(key, 0) + 1
                return None
    window_start = min(m.departure for m in missions)
    window_end = max(m.arrival for m in missions)
    for pid, roster in assigned.items():
        audit = pilot_ftl_checklist(roster, pilots[pid], avail, window_start, window_end)
        if not all(audit['checks'].values()) or audit['monthly_status'] == 'NIET OK':
            if failure_stats is not None:
                failed = [name for name,ok in audit['checks'].items() if not ok]
                if audit['monthly_status'] == 'NIET OK':
                    failed.append('monthly_two_48h_rest')
                key = ('FINAL', 'FTL_RECOVERY_OR_OTHER', '; '.join(failed))
                failure_stats[key] = failure_stats.get(key,0)+1
            return None
    return assign, counts, days, meta

def score(decoded,missions,pilots,avail,caps,fos):
    assign,counts,days,meta=decoded
    out_events=sum(1 for x in meta.values() if x['outstation'])
    out_changed=sum(x['changed_pilots'] for x in meta.values() if x['outstation'])

    vals=[]
    for pool in (caps,fos):
        c=[counts[p] for p in pool]; d=[len(days[p]) for p in pool]
        vals += [statistics.pvariance(c) if len(c)>1 else 0,
                 statistics.pvariance(d) if len(d)>1 else 0]
    balance=vals[0]+vals[2]+0.5*(vals[1]+vals[3])

    byday={}
    for m in missions: byday.setdefault(m.departure.date(),[]).append(m)
    reserve_short=0; reserve_total=0
    for day,ms in byday.items():
        active_c={assign[m.id]['captain'] for m in ms}; active_f={assign[m.id]['fo'] for m in ms}
        avc=sum(avail.get((p,day),'AVAILABLE') not in BLOCKING for p in caps)-len(active_c)
        avf=sum(avail.get((p,day),'AVAILABLE') not in BLOCKING for p in fos)-len(active_f)
        reserve_short += max(0,1-avc)+max(0,1-avf)
        reserve_total += max(0,avc)+max(0,avf)

    base_swaps=sum(1 for x in meta.values() if x['action'].startswith('BASE_') and 'SWAP' in x['action'])
    # Strict lexicographic priority.
    return (out_events,out_changed,balance,reserve_short,base_swaps,-reserve_total)

def backup_coverage_details(assign, missions, avail, caps, fos):
    """Explain exactly where the one-CAPT + one-FO reserve target is missed."""
    byday={}
    for m in missions:
        byday.setdefault(m.departure.date(),[]).append(m)
    details=[]
    for day,ms in sorted(byday.items()):
        active_c={assign[m.id]['captain'] for m in ms}
        active_f={assign[m.id]['fo'] for m in ms}
        available_c=[p for p in caps if avail.get((p,day),'AVAILABLE') not in BLOCKING]
        available_f=[p for p in fos if avail.get((p,day),'AVAILABLE') not in BLOCKING]
        reserve_c=[p for p in available_c if p not in active_c]
        reserve_f=[p for p in available_f if p not in active_f]
        cap_short=max(0,1-len(reserve_c)); fo_short=max(0,1-len(reserve_f))
        if cap_short or fo_short:
            details.append({
                'date':day.isoformat(),
                'captain_shortage':cap_short,'fo_shortage':fo_short,
                'available_captains':len(available_c),'active_captains':len(active_c),'reserve_captains':reserve_c,
                'available_fos':len(available_f),'active_fos':len(active_f),'reserve_fos':reserve_f,
                'missions':[m.id for m in ms],
            })
    return details

